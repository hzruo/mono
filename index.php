        $password = (string)($_POST['password'] ?? '');
        $u = one('SELECT * FROM app_users WHERE email=? OR nickname=? LIMIT 1', [$account, $account]);
        if ($u && password_verify($password, (string)$u['password'])) {
            start_login((int)$u['id']);
            set_flash('登录成功');
            go(route_url('home'));
        }
        err('账号或密码错误');
    }
    $form = '<form method="post">' . form_token()
        . input('邮箱或昵称', 'account', '', 'text', true)
        . input('密码', 'password', '', 'password', true)
        . '<button class="btn" type="submit">登录</button></form>';
    $body = '<div class="install-wrap"><div class="card"><h1 class="card-title" style="font-size:var(--font-size-xl)">管理员登录</h1>'
        . (string)hook('login.after_form', $form, []) . '</div></div>';
    page('登录', $body, [], true);
}
function logout_route(): void
{
    clear_auth_cookie();
    set_flash('已退出登录');
    go(route_url('login'));
}

// --- 19. RSS（核心内置，插件可覆盖）---
function rss_route(): void
{
    header('Content-Type: application/rss+xml; charset=utf-8');
    $posts = all('SELECT * FROM app_posts WHERE status=1 ORDER BY created_at DESC, id DESC LIMIT 20');
    $site = setting('site_name', 'Mono');
    $link = absolute_url(route_url('home'));
    $xml = '<?xml version="1.0" encoding="UTF-8"?><rss version="2.0"><channel>';
    $xml .= '<title>' . h($site) . '</title><link>' . h($link) . '</link><description>' . h(setting('site_description')) . '</description>';
    foreach ($posts as $p) {
        $url = absolute_url(route_url('post', ['id' => (int)$p['id']]));
        $xml .= '<item><title>' . h($p['title']) . '</title><link>' . h($url) . '</link><guid>' . h($url) . '</guid>'
            . '<pubDate>' . date(DATE_RSS, (int)$p['created_at']) . '</pubDate>'
            . '<description><![CDATA[' . post_excerpt((string)$p['content'], 300) . ']]></description></item>';
    }
    echo $xml . '</channel></rss>';
    exit;
}

