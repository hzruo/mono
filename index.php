function db_config(): array
{
    static $config;
    return $config ??= app_db_config(DB_CONFIG_FILE, DATA_DIR);
}
function db_driver(): string { return (string)db_config()['driver']; }
function db(): PDO
{
    static $db;
    return $db ??= app_db_connect(db_config());
}
function db_row_cache_clear(): void { $GLOBALS['__db_row_cache'] = []; }

function q(string $sql, array $p = []): PDOStatement
{
    if (strncasecmp(ltrim($sql), 'SELECT', 6) !== 0) db_row_cache_clear();
    $s = db()->prepare($sql);
    $s->execute($p);
    return $s;
}
function one(string $sql, array $p = []): ?array { $r = q($sql, $p)->fetch(); return $r ?: null; }
function all(string $sql, array $p = []): array { return q($sql, $p)->fetchAll(); }
function val(string $sql, array $p = []): mixed { return q($sql, $p)->fetchColumn(); }

function row(string $table, string $key, mixed $value): ?array
{
    $cache =& $GLOBALS['__db_row_cache'];
    if (!is_array($cache)) $cache = [];
    $cache_key = $table . "\0" . $key . "\0" . serialize($value);
    if (!array_key_exists($cache_key, $cache)) {
        $t = app_db_identifier(db_driver(), $table);
        $k = app_db_identifier(db_driver(), $key);
        $cache[$cache_key] = one("SELECT * FROM $t WHERE $k=?", [$value]) ?: false;
    }
    return $cache[$cache_key] ?: null;
}

function rows_by_ids(string $table, array $ids, string $cols = '*'): array
{
    $ids = array_values(array_unique(array_filter(array_map('intval', $ids))));
    if (!$ids) return [];
    $rows = q("SELECT $cols FROM $table WHERE id IN (" . sql_marks(count($ids)) . ')', $ids)->fetchAll();
    $map = [];
    foreach ($rows as $r) $map[(int)$r['id']] = $r;
    return $map;
}

function tx(callable $fn): mixed
{
    $db = db();
    if ($db->inTransaction()) return $fn();
    $sqlite = db_driver() === 'sqlite';
    if ($sqlite) $db->exec('BEGIN IMMEDIATE'); else $db->beginTransaction();
    try {
        $result = $fn();
        if ($sqlite) $db->exec('COMMIT'); else $db->commit();
        return $result;
    } catch (Throwable $e) {
        if ($sqlite) { try { $db->exec('ROLLBACK'); } catch (Throwable) {} }
        elseif ($db->inTransaction()) $db->rollBack();
        db_row_cache_clear();
        throw $e;
    }
}

