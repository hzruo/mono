// 按月归档统计：跨库使用各自的时间格式化函数（显式覆盖三驱动）。
function post_archive_counts(): array
{
    $expr = match (db_driver()) {
        'mysql' => "DATE_FORMAT(FROM_UNIXTIME(created_at),'%Y-%m')",
        'pgsql' => "to_char(to_timestamp(created_at),'YYYY-MM')",
        default => "strftime('%Y-%m',created_at,'unixepoch','localtime')",
    };
    $rows = all("SELECT $expr AS ym, COUNT(*) AS cnt FROM app_posts WHERE status=1 GROUP BY ym ORDER BY ym DESC LIMIT 24");
    $out = [];
    foreach ($rows as $r) {
        $ym = (string)$r['ym'];
        $out[] = ['ym' => $ym, 'label' => str_replace('-', ' 年 ', $ym) . ' 月', 'cnt' => (int)$r['cnt']];
    }
    return $out;
}


// --- 16. 文章数据与列表渲染 ---
function post_excerpt(string $content, ?int $max = null): string
{
    $max ??= max(20, (int)setting('excerpt_length', '160'));
    $plain = preg_replace('/```.*?```/s', ' ', $content) ?? $content;
    $plain = preg_replace('/[#>*`_\-\[\]()!]/', '', $plain) ?? $plain;
    $plain = trim(preg_replace('/\s+/', ' ', $plain) ?? '');
    return cut($plain, $max);
}

// 批量取回一组文章的标签，构建 post_id => tags 映射（避免列表 N+1）。
function posts_tags_map(array $post_ids): array
{
    $post_ids = array_values(array_unique(array_filter(array_map('intval', $post_ids))));
    if (!$post_ids) return [];
    $rows = all('SELECT pt.post_id,t.id,t.name FROM app_post_tags pt JOIN app_tags t ON t.id=pt.tag_id WHERE pt.post_id IN (' . sql_marks(count($post_ids)) . ')', $post_ids);
    $map = [];
    foreach ($rows as $r) $map[(int)$r['post_id']][] = ['id' => (int)$r['id'], 'name' => (string)$r['name']];
    return $map;
}

