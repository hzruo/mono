function hook_registry(): array
{
    if (is_array($GLOBALS['__hook_registry'] ?? null)) return $GLOBALS['__hook_registry'];
    $registry = [];
    foreach (plugins() as $plugin) {
        if (!plugin_enabled($plugin)) continue;
        foreach ((array)($plugin['hooks'] ?? []) as $name => $fn) {
            foreach (plugin_entry_definitions() as $entry => $def) {
                if ($name === $def['hook'] && !plugin_entry_enabled($plugin, $entry)) continue 2;
            }
            $registry[$name][] = ['plugin' => $plugin, 'fn' => $fn];
        }
    }
    return $GLOBALS['__hook_registry'] = $registry;
}

// Hook 管道：扩展返回新值以修改数据，返回 null 表示不修改。
function hook(string $name, mixed $value = null, array $ctx = []): mixed
{
    $registry = $GLOBALS['__hook_registry'] ?? hook_registry();
    $entries = $registry[$name] ?? null;
    if (!$entries) return $value;
    foreach ($entries as $entry) {
        $fn = $entry['fn'];
        $next = plugin_call($entry['plugin'], fn(): mixed => plugin_callback_exists($fn) ? $fn($value, $ctx) : null);
        if ($next !== null) $value = $next;
    }
    return $value;
}
function fire(string $name, array $ctx = []): void { hook($name, null, $ctx); }

// 插件路由分发：命中并已处理返回 true。
function plugin_route(string $action): bool
{
    foreach (plugins() as $plugin) {
        if (!plugin_enabled($plugin)) continue;
        $fn = $plugin['routes'][$action] ?? null;
        if ($fn === null) continue;
        $handled = plugin_call($plugin, function () use ($fn, $plugin): bool {
            if (!plugin_callback_exists($fn)) return false;
            $fn($plugin);
            return true;
        });
        if ($handled) return true;
    }
    return false;
}


// --- 8. URL 与路由 ---
function app_url(string $path = ''): string
{
    $path = ltrim($path, '/');
    $dir = rtrim(str_replace('\\', '/', dirname((string)($_SERVER['SCRIPT_NAME'] ?? '/index.php'))), '/');
    $base = ($dir === '' || $dir === '.') ? '' : $dir;
    if ($path === '') return $base === '' ? '/' : $base . '/';
    return $base . '/' . $path;
}
function append_url_query(string $url, array $params): string
{
    $query = [];
    foreach ($params as $k => $v) { if ($v === null || $v === '') continue; $query[$k] = (string)$v; }
    if (!$query) return $url;
    return $url . (str_contains($url, '?') ? '&' : '?') . http_build_query($query, '', '&', PHP_QUERY_RFC3986);
}
function index_url(array $params = []): string { return append_url_query(app_url('index.php'), $params); }
function admin_url(array $params = []): string { return route_url('admin', $params); }

// 统一路由 URL 生成：支持 ?a=action 与伪静态两种模式。
function route_url(string $a = 'home', array $params = []): string
{
    if (setting('pretty_url', '0') !== '1') return $a === 'home' ? index_url($params) : index_url(['a' => $a] + $params);
    if ($a === 'home') return $params ? append_url_query(app_url(''), $params) : app_url();
    $params = ['a' => $a] + $params;
    $segments = [];
    if (isset($params['a']) && $params['a'] !== '') { $segments[] = rawurlencode((string)$params['a']); unset($params['a']); }
    if (isset($params['id']) && ctype_digit((string)$params['id'])) { $segments[] = rawurlencode((string)$params['id']); unset($params['id']); }
    elseif ($a === 'page' && isset($params['slug']) && (string)$params['slug'] !== '') { $segments[] = rawurlencode((string)$params['slug']); unset($params['slug']); }
    return append_url_query(app_url(implode('/', $segments)), $params);
}
function asset_url(string $file): string { return app_url($file); }

// 解析伪静态路径，回填 $_GET['a'] 与 $_GET['id']。
function parse_path_route(): void
{
    $path = (string)(parse_url((string)($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH) ?? '');
    $script = str_replace('\\', '/', (string)($_SERVER['SCRIPT_NAME'] ?? '/index.php'));
    $base = rtrim(str_replace('\\', '/', dirname($script)), '/');
    if ($base !== '' && $base !== '.' && str_starts_with($path, $base . '/')) $path = substr($path, strlen($base));
    $path = trim($path, '/');
    if ($path === '' || $path === basename($script)) return;
    $segments = array_values(array_filter(explode('/', $path), 'strlen'));
    if (isset($segments[0]) && $segments[0] !== 'a' && !array_key_exists('a', $_GET)) $_GET['a'] = rawurldecode($segments[0]);
    if (isset($segments[1]) && !array_key_exists('id', $_GET)) {
        if (($segments[0] ?? '') === 'page') $_GET['slug'] = rawurldecode($segments[1]); else $_GET['id'] = rawurldecode($segments[1]);
    }
}

