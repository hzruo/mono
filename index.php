// 轻量服务端代码高亮：按语言族用有序正则分词，输出 tok-* span（零依赖、无外部库）。
function code_token_patterns(string $lang): array
{
    $str_dq = '"[^"\n]*"';
    $str_sq = "'[^'\n]*'";
    $str_both = $str_dq . '|' . $str_sq;
    $num = '\b0[xXbB][0-9a-fA-F_]+\b|\b\d+(?:\.\d+)?\b';
    $type = '\b[A-Z][A-Za-z0-9_]*\b';
    $fn = '\b[a-z_][A-Za-z0-9_]*(?=\s*\()';
    switch ($lang) {
        case 'php':
            return [
                ['\/\/[^\n]*|#[^\n]*|\/\*.*?\*\/', 'com'],
                [$str_both, 'str'],
                ['\$[A-Za-z_]\w*', 'var'],
                [$num, 'num'],
                ['\b(?:abstract|array|as|break|callable|case|catch|class|clone|const|continue|declare|default|do|echo|else|elseif|empty|enum|extends|final|finally|fn|for|foreach|function|global|goto|if|implements|include|instanceof|insteadof|interface|isset|list|match|namespace|new|print|private|protected|public|readonly|require|return|static|switch|throw|trait|try|unset|use|var|while|yield|null|true|false)\b', 'kw'],
                [$type, 'type'],
                [$fn, 'fn'],
            ];
        case 'js': case 'javascript': case 'ts': case 'typescript': case 'jsx': case 'tsx':
            return [
                ['\/\/[^\n]*|\/\*.*?\*\/', 'com'],
                [$str_both . '|`[^`]*`', 'str'],
                [$num, 'num'],
                ['\b(?:async|await|break|case|catch|class|const|continue|debugger|default|delete|do|else|enum|export|extends|finally|for|from|function|get|if|implements|import|in|instanceof|interface|let|new|of|package|private|protected|public|return|set|static|super|switch|this|throw|try|type|typeof|var|void|while|with|yield|null|true|false|undefined)\b', 'kw'],
                [$type, 'type'],
                [$fn, 'fn'],
            ];
        case 'c': case 'cpp': case 'java': case 'cs': case 'go': case 'rust': case 'kotlin': case 'swift':
            return [
                ['\/\/[^\n]*|\/\*.*?\*\/', 'com'],
                [$str_both, 'str'],
                [$num, 'num'],
                ['\b(?:auto|bool|break|case|char|class|const|continue|default|do|double|else|enum|extern|float|for|func|fun|goto|if|int|interface|long|map|new|package|public|private|protected|return|short|signed|sizeof|static|struct|switch|typedef|union|unsigned|use|var|void|volatile|while|null|true|false|nil|None)\b', 'kw'],
                [$type, 'type'],
                [$fn, 'fn'],
            ];
        case 'css': case 'scss': case 'less':
            return [
                ['\/\*.*?\*\/', 'com'],
                [$str_both, 'str'],
                ['@[\w-]+', 'kw'],
                ['[\w-]+(?=\s*:)', 'attr'],
                ['#[0-9a-fA-F]{3,8}\b|\b\d+(?:\.\d+)?(?:px|em|rem|%|vh|vw|vmin|vmax|s|ms|fr)?\b', 'num'],
                ['\.[-\w]+', 'type'],
                ['::{1,2}[\w-]+', 'fn'],
            ];
        case 'html': case 'xml': case 'svg': case 'vue':
            return [
                ['<!--.*?-->', 'com'],
                ['<!.*?>', 'kw'],
                ['<\/?[a-zA-Z][\w:-]*|/?>', 'tag'],
                ['[\w:-]+(?=\s*=)', 'attr'],
                [$str_both, 'str'],
            ];
        case 'sql':
            return [
                ['--[^\n]*|\/\*.*?\*\/', 'com'],
                [$str_sq, 'str'],
                ['\b(?i:select|from|where|insert|into|values|update|set|delete|create|table|drop|alter|add|index|unique|primary|key|foreign|references|join|left|right|inner|outer|on|group|by|order|asc|desc|limit|offset|having|distinct|as|and|or|not|null|is|in|like|ilike|between|exists|union|all|count|sum|avg|min|max|begin|commit|rollback)\b', 'kw'],
                [$num, 'num'],
                [$fn, 'fn'],
            ];
        case 'sh': case 'bash': case 'shell': case 'zsh':
            return [
                ['#[^\n]*', 'com'],
                [$str_both, 'str'],
                ['\$\{?[#@*?0-9A-Za-z_]+\}?', 'var'],
                ['\b(?:if|then|else|elif|fi|for|while|until|do|done|case|esac|function|return|exit|export|local|source|in)\b', 'kw'],
                ['-{1,2}[\w-]+', 'attr'],
                [$num, 'num'],
            ];
        case 'json':
            return [
                ['"[^"\n]*"(?=\s*:)', 'attr'],
                ['"[^"\n]*"', 'str'],
                ['\b(?:true|false|null)\b', 'kw'],
                ['-?\b\d+(?:\.\d+)?(?:[eE][+-]?\d+)?\b', 'num'],
            ];
        case 'py': case 'python':
            return [
                ['#[^\n]*', 'com'],
                ['"""[\s\S]*?"""|' . $str_both, 'str'],
                ['\b(?:def|class|return|if|elif|else|for|while|import|from|as|with|try|except|finally|raise|pass|break|continue|lambda|yield|global|nonlocal|assert|del|in|is|not|and|or|None|True|False|async|await|self)\b', 'kw'],
                [$type, 'type'],
                [$fn, 'fn'],
                [$num, 'num'],
            ];
        case 'yaml': case 'yml':
            return [
                ['#[^\n]*', 'com'],
                ['(?m)^[\s-]*[\w.-]+(?=\s*:)', 'attr'],
                [$str_both, 'str'],
                ['\b(?:true|false|null|yes|no|on|off)\b', 'kw'],
                [$num, 'num'],
            ];
        default:
            return [];
    }
}

// 将原始代码按语言分词并转义输出；未知语言仅转义不高亮。
function code_highlight(string $code, string $lang): string
{
    $pats = code_token_patterns($lang);
    if (!$pats) return h($code);
    $alt = [];
    foreach ($pats as $p) $alt[] = '(' . $p[0] . ')';
    $regex = '/' . implode('|', $alt) . '/s';
    $out = '';
    $last = 0;
    if (preg_match_all($regex, $code, $m, PREG_OFFSET_CAPTURE | PREG_SET_ORDER) > 0) {
        foreach ($m as $set) {
            $text = $set[0][0];
            $offset = $set[0][1];
            if ($offset > $last) $out .= h(substr($code, $last, $offset - $last));
            $cls = 'plain';
            for ($i = 1; $i < count($set); $i++) {
                if (($set[$i][1] ?? -1) !== -1) { $cls = $pats[$i - 1][1]; break; }
            }
            $out .= '<span class="tok-' . $cls . '">' . h($text) . '</span>';
            $last = $offset + strlen($text);
        }
    }
    return $out . h(substr($code, $last));
}

function markdown_html(string $text): string
{
    $text = (string)hook('markdown.render', $text, []);
    // 提取代码块：服务端高亮 + 语言标签/复制按钮外壳，避免内部被其它规则破坏。
    $blocks = [];
    $text = preg_replace_callback('/```(\w*)\n(.*?)```/s', function ($m) use (&$blocks) {
        $lang = strtolower($m[1]);
        $raw = rtrim($m[2], "\n");
        $label = $lang !== '' ? $lang : 'text';
        $blocks[] = '<div class="codeblock" data-lang="' . h($label) . '">'
            . '<div class="codeblock-bar"><span class="codeblock-lang">' . h($label) . '</span>'
            . '<button type="button" class="codeblock-copy">复制</button></div>'
            . '<pre><code' . ($lang !== '' ? ' class="language-' . h($lang) . '"' : '') . '>' . code_highlight($raw, $lang) . '</code></pre></div>';
        return "\x00BLOCK" . (count($blocks) - 1) . "\x00";
    }, $text) ?? $text;

    $text = h($text);
    // 标题
    $text = preg_replace('/^######\s+(.*$)/m', '<h6>$1</h6>', $text) ?? $text;
    $text = preg_replace('/^#####\s+(.*$)/m', '<h5>$1</h5>', $text) ?? $text;
    $text = preg_replace('/^####\s+(.*$)/m', '<h4>$1</h4>', $text) ?? $text;
    $text = preg_replace('/^###\s+(.*$)/m', '<h3>$1</h3>', $text) ?? $text;
    $text = preg_replace('/^##\s+(.*$)/m', '<h2>$1</h2>', $text) ?? $text;
    $text = preg_replace('/^#\s+(.*$)/m', '<h1>$1</h1>', $text) ?? $text;
    // 分割线
    $text = preg_replace('/^(\-{3,}|\*{3,})$/m', '<hr>', $text) ?? $text;
    // 引用
    $text = preg_replace('/^&gt;\s+(.*$)/m', '<blockquote>$1</blockquote>', $text) ?? $text;
    // 图片与链接
    $text = preg_replace('/!\[(.*?)\]\((https?:\/\/[^\s)]+)\)/', '<img src="$2" alt="$1">', $text) ?? $text;
    $text = preg_replace('/\[(.*?)\]\((https?:\/\/[^\s)]+)\)/', '<a href="$2" target="_blank" rel="noopener nofollow">$1</a>', $text) ?? $text;
    // 粗体、斜体、行内代码
    $text = preg_replace('/\*\*(.+?)\*\*/s', '<strong>$1</strong>', $text) ?? $text;
    $text = preg_replace('/(?<!\*)\*([^*\n]+?)\*(?!\*)/', '<em>$1</em>', $text) ?? $text;
    $text = preg_replace('/`([^`\n]+?)`/', '<code>$1</code>', $text) ?? $text;
    // 无序列表
    $text = preg_replace_callback('/(?:^|\n)((?:[-*]\s+.*\n?)+)/', function ($m) {
        $items = preg_split('/\n/', trim($m[1]));
        $li = '';
        foreach ($items as $it) { $it = preg_replace('/^[-*]\s+/', '', $it); $li .= '<li>' . $it . '</li>'; }
        return "\n<ul>$li</ul>";
    }, $text) ?? $text;
    // 段落与换行
    $text = nl2br($text);
    $text = preg_replace('/<br\s*\/?>\s*(<\/?(?:h[1-6]|ul|li|blockquote|pre|hr|img)[^>]*>)/', '$1', $text) ?? $text;
    // 还原代码块
    $text = preg_replace_callback('/\x00BLOCK(\d+)\x00/', fn($m) => $blocks[(int)$m[1]] ?? '', $text) ?? $text;

    return (string)hook('markdown.after', $text, []);
}


