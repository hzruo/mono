// --- 13. 分页 ---
function paginate(int $total, int $page, int $size, callable $url_fn): string
{
    $pages = (int)ceil($total / max(1, $size));
    if ($pages <= 1) return '';
    $page = max(1, min($page, $pages));
    $html = '<div class="pager">';
    if ($page > 1) $html .= '<a href="' . h($url_fn($page - 1)) . '">上一页</a>';
    $window = 2;
    $start = max(1, $page - $window); $end = min($pages, $page + $window);
    if ($start > 1) { $html .= '<a href="' . h($url_fn(1)) . '">1</a>'; if ($start > 2) $html .= '<span class="gap">…</span>'; }
    for ($i = $start; $i <= $end; $i++) {
        $html .= $i === $page ? '<span class="current">' . $i . '</span>' : '<a href="' . h($url_fn($i)) . '">' . $i . '</a>';
    }
    if ($end < $pages) { if ($end < $pages - 1) $html .= '<span class="gap">…</span>'; $html .= '<a href="' . h($url_fn($pages)) . '">' . $pages . '</a>'; }
    if ($page < $pages) $html .= '<a href="' . h($url_fn($page + 1)) . '">下一页</a>';
    return $html . '</div>';
}

