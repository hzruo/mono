// --- 17. 文章写入（标签同步、before/after save Hook）---
// 解析逗号/空格分隔的标签串，写入 app_tags 与 app_post_tags（整篇一次性，非循环查库放大）。
function sync_post_tags(int $post_id, string $tags_input): void
{
    q('DELETE FROM app_post_tags WHERE post_id=?', [$post_id]);
    $names = array_values(array_unique(array_filter(array_map(
        fn($t) => mb_substr(trim($t), 0, 40),
        preg_split('/[,，\s]+/u', $tags_input) ?: []
    ))));
    foreach ($names as $name) {
        app_db_upsert('app_tags', ['name' => $name, 'slug' => slugify($name) ?: md5($name)], ['name']);
        $tid = (int)val('SELECT id FROM app_tags WHERE name=?', [$name]);
        if ($tid > 0) app_db_insert_ignore('app_post_tags', ['post_id' => $post_id, 'tag_id' => $tid], ['post_id', 'tag_id']);
    }
}

// 保存文章（新建或编辑），返回文章 ID。$data 已过滤。
function save_post(array $data, int $post_id = 0): int
{
    $data = hook('post.before_save', $data, ['post_id' => $post_id]);
    if (!is_array($data)) err('保存数据无效');
    $tags_input = (string)($data['tags'] ?? '');
    $row = [
        'user_id' => (int)($data['user_id'] ?? uid()),
        'title' => mb_substr((string)$data['title'], 0, DB_STRING_MAX_LENGTH),
        'content' => (string)$data['content'],
        'category_id' => (int)($data['category_id'] ?? 0),
        'status' => (int)($data['status'] ?? 1) === 1 ? 1 : 0,
        'updated_at' => now(),
    ];
    // 文章级评论开关：仅评论插件启用时由写文章页提交；未启用时不动该列（保留原值/默认 1）。
    if (array_key_exists('allow_comment', $data)) $row['allow_comment'] = (int)$data['allow_comment'] === 1 ? 1 : 0;
    if ($post_id > 0) {
        $fields = array_keys($row);
        q('UPDATE app_posts SET ' . implode('=?,', $fields) . '=? WHERE id=?', array_merge(array_values($row), [$post_id]));
    } else {
        $row['created_at'] = now();
        $row['view_count'] = 0;
        $cols = array_keys($row);
        q('INSERT INTO app_posts(' . implode(',', $cols) . ') VALUES(' . sql_marks(count($cols)) . ')', array_values($row));
        $post_id = app_db_last_insert_id('app_posts');
    }
    sync_post_tags($post_id, $tags_input);
    fire('post.after_save', ['post_id' => $post_id, 'data' => $row]);
    return $post_id;
}

