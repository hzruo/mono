function cut(string $v, int $max): string
{
    $v = trim($v);
    return mb_strlen($v) > $max ? mb_substr($v, 0, $max) . '…' : $v;
}

function human_time(int $ts): string
{
    $diff = time() - $ts;
    if ($diff < 60) return '刚刚';
    if ($diff < 3600) return floor($diff / 60) . ' 分钟前';
    if ($diff < 86400) return floor($diff / 3600) . ' 小时前';
    if ($diff < 2592000) return floor($diff / 86400) . ' 天前';
    return date('Y-m-d', $ts);
}

// 依据种子（邮箱/昵称/IP）确定性生成 identicon 风格 SVG 头像，返回 data URI。
// 零依赖、不请求外部服务：同一 seed 永远得到同一头像，5x5 网格左右镜像对称。
function avatar_svg(string $seed, int $size = 64): string
{
    $seed = strtolower(trim($seed));
    if ($seed === '') $seed = 'mono';
    $size = max(16, min(256, $size));
    $hash = hash('sha256', $seed);
    $hue = hexdec(substr($hash, 0, 3)) % 360;
    $hue2 = ($hue + 32) % 360;
    $bg = sprintf('hsl(%d,52%%,95%%)', $hue);
    $fg = sprintf('hsl(%d,58%%,50%%)', $hue);
    $fg2 = sprintf('hsl(%d,58%%,62%%)', $hue2);
    $grid = 5;
    $cell = $size / $grid;
    $r = round($cell * 0.24, 2);
    $cells = '';
    for ($row = 0; $row < $grid; $row++) {
        for ($col = 0; $col < 3; $col++) {
            $bit = hexdec($hash[$row * 3 + $col]);
            if ($bit < 7) continue;
            $fill = ($bit % 2 === 0) ? $fg : $fg2;
            $y = round($row * $cell, 2);
            foreach ([$col, $grid - 1 - $col] as $c) {
                if ($c < $col) continue; // 仅镜像一次（中心列不重复）
                $cells .= '<rect x="' . round($c * $cell, 2) . '" y="' . $y . '" width="' . round($cell, 2) . '" height="' . round($cell, 2) . '" rx="' . $r . '" fill="' . $fill . '"/>';
            }
        }
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" width="' . $size . '" height="' . $size . '" viewBox="0 0 ' . $size . ' ' . $size . '">'
        . '<rect width="' . $size . '" height="' . $size . '" fill="' . $bg . '"/>' . $cells . '</svg>';
}

function avatar_url(string $seed, int $size = 64): string
{
    return 'data:image/svg+xml,' . rawurlencode(avatar_svg($seed, $size));
}

// 自定义头像：app_users.avatar 列存扩展名（空串=默认 identicon），文件落盘 DATA_DIR/avatars/avatar-<id>.<ext>。
function avatar_dir(): string { return DATA_DIR . '/avatars'; }
function avatar_file(int $uid, string $ext): string { return avatar_dir() . '/avatar-' . $uid . '.' . $ext; }
function avatar_mime(string $ext): string { return ['png' => 'image/png', 'jpg' => 'image/jpeg', 'gif' => 'image/gif', 'webp' => 'image/webp'][$ext] ?? ''; }

// 用户头像 URL：有自定义头像走输出路由，否则回退种子 identicon。
function user_avatar_url(?array $user, int $size = 64): string
{
    $ext = $user ? (string)($user['avatar'] ?? '') : '';
    if ($ext !== '' && avatar_mime($ext) !== '' && is_file(avatar_file((int)$user['id'], $ext))) return route_url('avatar', ['id' => (int)$user['id']]);
    return avatar_url($user && (string)($user['email'] ?? '') !== '' ? (string)$user['email'] : (string)($user['nickname'] ?? 'mono'), $size);
}

// 头像输出路由：Content-Type 白名单映射 + 浏览器缓存，不暴露真实文件路径。
function avatar_route(): void
{
    $u = row('app_users', 'id', req_id());
    $ext = (string)($u['avatar'] ?? '');
    $mime = avatar_mime($ext);
    $file = $u && $mime !== '' ? avatar_file((int)$u['id'], $ext) : '';
    if (!$u || $file === '' || !is_file($file)) err('头像不存在', 404);
    header('Content-Type: ' . $mime);
    header('Content-Length: ' . (string)filesize($file));
    header('Cache-Control: public, max-age=86400');
    readfile($file);
    exit;
}

function slugify(string $text): string
{
    $text = strtolower(trim($text));
    $text = preg_replace('/[^a-z0-9]+/u', '-', $text) ?? '';
    return trim($text, '-') ?: '';
}


// --- 5. Cookie / 认证 / CSRF ---
function auth_cookie_secure(): bool
{
    return (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (string)($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https';
}
function app_cookie(string $name, string $value, int $expires, bool $httponly = true): void
{
    setcookie($name, $value, ['expires' => $expires, 'path' => '/', 'secure' => auth_cookie_secure(), 'httponly' => $httponly, 'samesite' => 'Lax']);
}
function auth_cookie_clear(): void { app_cookie(AUTH_COOKIE_NAME, '', time() - 3600); unset($_COOKIE[AUTH_COOKIE_NAME]); }
function csrf_cookie_clear(): void { app_cookie(CSRF_COOKIE_NAME, '', time() - 3600); unset($_COOKIE[CSRF_COOKIE_NAME]); }

function auth_cookie_set(int $user_id, string $password_hash): void
{
    $expire = time() + COOKIE_TTL;
    $signature = hash_hmac('sha256', $user_id . '|' . $expire, $password_hash);
    app_cookie(AUTH_COOKIE_NAME, $user_id . '.' . $expire . '.' . $signature, $expire);
}
function auth_cookie_parts(): ?array
{
    $value = (string)($_COOKIE[AUTH_COOKIE_NAME] ?? '');
    if (!preg_match('/^(\d+)\.(\d+)\.([a-f0-9]{64})$/D', $value, $m)) return null;
    $id = (int)$m[1]; $expire = (int)$m[2];
    return $id > 0 && $expire > 0 ? ['id' => $id, 'expire' => $expire, 'signature' => $m[3]] : null;
}
function csrf_token(): string
{
    static $token = null;
    if ($token !== null) return $token;
    $token = (string)($_COOKIE[CSRF_COOKIE_NAME] ?? '');
    if (!preg_match('/^[a-f0-9]{64}$/D', $token)) {
        $token = bin2hex(random_bytes(32));
        app_cookie(CSRF_COOKIE_NAME, $token, time() + COOKIE_TTL, false);
        $_COOKIE[CSRF_COOKIE_NAME] = $token;
    }
    return $token;
}

// 当前登录用户（无状态 HMAC Cookie 认证，请求级缓存）。
function me(): ?array
{
    if (array_key_exists('__me_cache', $GLOBALS)) return is_array($GLOBALS['__me_cache']) ? $GLOBALS['__me_cache'] : null;
    $parts = auth_cookie_parts();
    if (!$parts || $parts['expire'] < time()) { if ($parts) auth_cookie_clear(); return $GLOBALS['__me_cache'] = null; }
    $u = row('app_users', 'id', $parts['id']);
    $expected = $u ? hash_hmac('sha256', $parts['id'] . '|' . $parts['expire'], (string)$u['password']) : '';
    if (!$u || !hash_equals($expected, $parts['signature'])) { clear_auth_cookie(); return $GLOBALS['__me_cache'] = null; }
    $GLOBALS['__request_uid'] = (int)$u['id'];
    return $GLOBALS['__me_cache'] = $u;
}
function uid(): int
{
    if (array_key_exists('__request_uid', $GLOBALS)) return (int)$GLOBALS['__request_uid'];
    $u = me();
    return $u ? (int)$u['id'] : 0;
}
